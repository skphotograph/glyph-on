export const languageOf = (setting, locale) => setting === 'ja' || setting !== 'en' && /^ja\b/i.test(locale ?? '') ? 'ja' : 'en';
export function translate(language, key, values = {}) {
  const phrase = messages[key]?.[language === 'ja' ? 1 : 0] ?? messages.operationFailed[language === 'ja' ? 1 : 0];
  return phrase.replace(/\{(\w+)\}/g, (full, field) => Object.hasOwn(values, field) ? String(values[field]) : full);
}
